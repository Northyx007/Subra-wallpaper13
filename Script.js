let favs=JSON.parse(
  localStorage.getItem('mapenziFavs')||'[]'
);

let current=null;

const $=id=>document.getElementById(id);

const views=n=>
  n>=1000
  ?(n/1000).toFixed(1)+'K'
  :n;

function toast(t){

  $('toast').textContent=t;

  $('toast').classList.add('show');

  clearTimeout(window.tt);

  window.tt=setTimeout(
    ()=>$('toast').classList.remove('show'),
    2200
  );
}

function save(){

  localStorage.setItem(
    'mapenziFavs',
    JSON.stringify(favs)
  );

}

function isFav(id){

  return favs.includes(id);

}

function toggleFav(id){

  favs=isFav(id)
    ?favs.filter(x=>x!==id)
    :[...favs,id];

  save();

  render();

  if(current?.id===id)
    updateModalFav();

  toast(
    isFav(id)
    ?'Added to Favorites ♥'
    :'Removed from Favorites'
  );
}

function card(w){

  const e=document.createElement('article');

  e.className='card';

  e.innerHTML=`

    <img
      src="${w.image}"
      loading="lazy"
      alt="${w.title}"
    >

    <div class="card-info">

      <div>

        <div class="card-title">
          ${w.title}
        </div>

        <div class="card-meta">
          ${w.category} · ${views(w.views)} views
        </div>

      </div>

      <div class="card-actions">

        <button class="fav ${
          isFav(w.id)?'active':''
        }">
          ${isFav(w.id)?'♥':'♡'}
        </button>

        <button class="share">
          ↗
        </button>

        <button class="dl">
          ↓
        </button>

      </div>

    </div>
  `;

  e.onclick=x=>{
    if(x.target.closest('button'))return;
    openPreview(w);
  };

  e.querySelector('.fav').onclick=x=>{
    x.stopPropagation();
    toggleFav(w.id);
  };

  e.querySelector('.share').onclick=x=>{
    x.stopPropagation();
    share(w);
  };

  e.querySelector('.dl').onclick=x=>{
    x.stopPropagation();
    download(w);
  };

  return e;
}

function grid(id,list){

  const box=$(id);

  box.innerHTML='';

  if(!list.length){

    box.innerHTML=`
      <div class="empty">
        <b>No wallpapers found</b>
        <span>
          Try another search or category.
        </span>
      </div>
    `;

    return;
  }

  list.forEach(
    w=>box.appendChild(card(w))
  );
}

function renderCats(){

  $('categoriesGrid').innerHTML='';

  cats.forEach(
    ([name,emoji])=>{

      const n=
        wallpapers.filter(
          w=>w.category===name
        ).length;

      const b=document.createElement('button');

      b.className='category';

      b.innerHTML=`
        <span class="emoji">${emoji}</span>
        <b>${name}</b>
        <small>${n} wallpapers</small>
      `;

      b.onclick=()=>{
        results(
          name+' Wallpapers',
          wallpapers.filter(
            w=>w.category===name
          )
        );
      };

      $('categoriesGrid')
        .appendChild(b);

    }
  );
}

function render(){

  $('count').textContent=
    wallpapers.length;

  renderCats();

  grid(
    'popularGrid',
    [...wallpapers]
      .sort((a,b)=>b.views-a.views)
      .slice(0,10)
  );

  grid(
    'latestGrid',
    [...wallpapers]
      .reverse()
      .slice(0,10)
  );

  grid(
    'favoritesGrid',
    wallpapers.filter(
      w=>isFav(w.id)
    )
  );
}

function results(title,list){

  $('results').style.display='block';

  $('resultsTitle').textContent=title;

  grid('resultsGrid',list);

  $('results').scrollIntoView({
    behavior:'smooth'
  });
}

function search(q){

  q=q.trim().toLowerCase();

  if(!q){

    $('results').style.display='none';

    return;
  }

  results(
    'Results for "'+q+'"',

    wallpapers.filter(w=>

      w.title.toLowerCase().includes(q) ||

      w.category.toLowerCase().includes(q) ||

      w.tags.some(
        t=>t.includes(q)
      )

    )
  );
}

function openPreview(w){

  current=w;

  $('preview').classList.add('open');

  document.body.style.overflow='hidden';

  $('mImg').src=w.image;

  $('mTitle').textContent=w.title;

  $('mCat').textContent=w.category;

  $('mRes').textContent=w.res;

  $('mSize').textContent=w.size;

  $('mViews').textContent=
    views(w.views);

  updateModalFav();

  $('related').innerHTML='';

  wallpapers
    .filter(
      x=>
        x.category===w.category &&
        x.id!==w.id
    )
    .slice(0,4)
    .forEach(x=>{

      const im=
        document.createElement('img');

      im.src=x.image;

      im.loading='lazy';

      im.onclick=()=>{
        openPreview(x);
      };

      $('related')
        .appendChild(im);

    });
}

function closePreview(){

  $('preview').classList.remove('open');

  document.body.style.overflow='';

}

function updateModalFav(){

  $('mFav').textContent=
    isFav(current.id)
    ?'♥'
    :'♡';

  $('mFav').style.color=
    isFav(current.id)
    ?'var(--pink)'
    :'#fff';
}

function download(w){

  const a=document.createElement('a');

  a.href=w.image;

  a.target='_blank';

  a.rel='noopener';

  a.download=
    w.title
      .replace(/[^a-z0-9]+/gi,'-')
      .toLowerCase()+'.jpg';

  document.body.appendChild(a);

  a.click();

  a.remove();

  toast('Opening wallpaper...');

}

async function share(w){

  if(navigator.share){

    try{

      await navigator.share({

        title:
          w.title+
          ' - MAPENZI WALLPAPER',

        text:
          'Check out this wallpaper',

        url:w.image

      });

    }catch(e){}

  }else{

    try{

      await navigator.clipboard
        .writeText(w.image);

      toast('Image link copied');

    }catch(e){

      toast('Share not supported');

    }

  }
}

